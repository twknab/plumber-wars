export const FONT_CHARS = Object.keys(G).join('') + ' ';

function build(scene, key, outlined, shadow) {
  const pad = outlined || shadow ? 1 : 0, ch = 7 + pad * 2, cols = 16;
  const keys = Object.keys(G);
  const cellW = 5 + pad * 2 + 1, rows = Math.ceil((keys.length + 1) / cols);
  const p = new PX(cols * cellW, rows * (ch + 1));
  const chars = {};
  keys.forEach((k, idx) => {
    const lines = G[k].split('|'); const gw = lines[0].length;
    const cx = (idx % cols) * cellW, cy = Math.floor(idx / cols) * (ch + 1);
    lines.forEach((ln, j) => { for (let i = 0; i < gw; i++) if (ln[i] === '#') p.px(cx + pad + i, cy + pad + j, C.white); });
    chars[k.charCodeAt(0)] = { x: cx, y: cy, width: gw + pad * 2, height: ch, xAdvance: gw + 1, xOffset: -pad, yOffset: -pad };
  });
  if (outlined) p.outline(C.ink, true);
  if (shadow) { const src = p.buf.slice(); const ink = 0xff000000 | 0x251418; for (let y = p.h - 2; y >= 0; y--) for (let x = p.w - 2; x >= 0; x--) if ((src[y * p.w + x] >>> 24) && !(src[(y + 1) * p.w + x + 1] >>> 24)) p.buf[(y + 1) * p.w + x + 1] = ink; for (let y = p.h - 2; y >= 0; y--) for (let x = 0; x < p.w; x++) if ((src[y * p.w + x] >>> 24) && !(p.buf[(y + 1) * p.w + x] >>> 24)) p.buf[(y + 1) * p.w + x] = ink; }
  const tex = p.toTexture(scene, key);
  const TW = p.w, TH = p.h;
  chars[32] = { x: 0, y: 0, width: 0, height: 0, xAdvance: 3, xOffset: 0, yOffset: 0 };
  const data = { retroFont: true, font: key, size: 7, lineHeight: 10 + pad, chars: {} };
  for (const code in chars) {
    const c = chars[code];
    data.chars[code] = { ...c, centerX: c.width >> 1, centerY: c.height >> 1, data: {}, kerning: {},
      u0: c.x / TW, v0: c.y / TH, u1: (c.x + c.width) / TW, v1: (c.y + c.height) / TH };
  }
  scene.cache.bitmapFont.add(key, { data, texture: key, frame: null });
  return tex;
}

export function buildFonts(scene) { build(scene, 'px', false); build(scene, 'pxo', true); build(scene, 'pxs', false, true); }

// Map arbitrary strings onto the glyph set.
export function clean(s) {
  return String(s).toUpperCase().replace(/[’‘]/g, "'").replace(/[“”]/g, '"').replace(/[—–]/g, '-').replace(/…/g, '...')
    .split('').map(c => (G[c] || c === ' ' || c === '\n') ? c : '').join('');
}
