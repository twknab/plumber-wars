const RECENT_KEY = 'recentReviews';
function fresh(pool) {
  const recent = store.get(RECENT_KEY, []);
  const options = pool.filter(r => !recent.includes(r));
  const pickFrom = options.length ? options : pool;
  const line = pickFrom[Math.floor(Math.random() * pickFrom.length)];
  store.set(RECENT_KEY, [line, ...recent].slice(0, 14));
  return line;
}

// Job-specific line most of the time (always the first time you see a job), generic otherwise.
export function pickReview(ji) {
  const own = JOB_REVIEWS[ji] || [];
  const seenJob = store.get('reviewedJobs', []);
  const useOwn = own.length && (!seenJob.includes(ji) || Math.random() < 0.6);
  if (!seenJob.includes(ji)) store.set('reviewedJobs', [...seenJob, ji]);
  return fresh(useOwn ? own : REVIEWS);
}

// Bumps the running five-star count and returns a neighborhood post about it.
export function pickBuzz(districtName, road) {
  const n = store.get('fiveStarCount', 11) + 1; // G's had a few before you showed up
  store.set('fiveStarCount', n);
  const [who, text] = BUZZ.filter(b => !store.get('recentBuzz', []).includes(b[0]))[Math.floor(Math.random() * 6)] || BUZZ[Math.floor(Math.random() * BUZZ.length)];
  store.set('recentBuzz', [who, ...store.get('recentBuzz', [])].slice(0, 5));
  return { who, text: text.replace('{n}', n).replace('{d}', districtName).replace('{road}', road || 'MARKET ST'), count: n };
}
